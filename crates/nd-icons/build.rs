//! Turns the vendored Lucide SVGs (`lucide/icons`, see `scripts/vendor-lucide`) into drawing
//! segments, so no backend parses SVG at run time.

#![allow(dead_code)]

use std::fmt::Write as _;
use std::path::Path;

#[path = "src/svg.rs"]
mod svg;

fn main() {
    println!("cargo:rerun-if-changed=lucide");
    println!("cargo:rerun-if-changed=src/svg.rs");
    let dir = Path::new("lucide/icons");
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .expect("lucide/icons exists; run scripts/vendor-lucide")
        .map(|e| e.expect("readable entry").path())
        .filter(|p| p.extension().is_some_and(|e| e == "svg"))
        .map(|p| p.file_stem().expect("file name").to_string_lossy().into_owned())
        .collect();
    names.sort();

    let mut out = String::from("// Generated by build.rs from lucide/icons.\n&[\n");
    for name in &names {
        let text = std::fs::read_to_string(dir.join(format!("{name}.svg"))).expect("readable svg");
        let (pieces, view) = svg::parse(&text).unwrap_or_else(|e| panic!("{name}.svg: {e}"));
        assert_eq!(view, 24., "{name}.svg is not on the 24 unit grid");
        write!(out, "(\"{name}\", &[").unwrap();
        for piece in &pieces {
            write!(out, "Path {{ filled: {}, segs: &[", piece.filled).unwrap();
            for seg in &piece.segs {
                match *seg {
                    svg::Seg::Move(x, y) => write!(out, "M({},{}),", n(x), n(y)),
                    svg::Seg::Line(x, y) => write!(out, "L({},{}),", n(x), n(y)),
                    svg::Seg::Cubic(a, b, c, d, e, f) => {
                        write!(out, "C({},{},{},{},{},{}),", n(a), n(b), n(c), n(d), n(e), n(f))
                    }
                    svg::Seg::Close => write!(out, "Z,"),
                }
                .unwrap();
            }
            out.push_str("] },");
        }
        out.push_str("]),\n");
    }
    out.push_str("]\n");
    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("lucide.rs");
    std::fs::write(dest, out).expect("write lucide.rs");
}

/// Four decimals is far below a pixel at any icon size.
fn n(v: f32) -> String {
    let r = (v * 1e4).round() / 1e4;
    let mut s = format!("{r}");
    if !s.contains('.') && !s.contains('e') {
        s.push_str(".0");
    }
    s
}
