//! Nix side of the settings: option paths, literals ("Copy as Nix"), and the generator that turns
//! a settings JSON Schema into the typed options of the home-manager module.
//!
//! Every generated option is `nullOr T` with default `null`. The module drops nulls before it
//! renders `config.toml`, so only keys a user set reach the file, and the app's own defaults
//! (and the "Managed by Nix" marking) stay accurate for everything else.

use serde_json::Value;

use crate::schema::{Prop, Ty, root_props};

/// `programs.<app>.settings.<key>` with attribute names quoted where Nix needs it.
pub fn option_path(app: &str, key: &str) -> String {
    let mut out = format!("programs.{}.settings", attr(app));
    for segment in key.split('.') {
        out.push('.');
        out.push_str(&attr(segment));
    }
    out
}

fn attr(name: &str) -> String {
    let bare = name.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '\''));
    if bare { name.to_owned() } else { string(name) }
}

fn string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '$' if chars.peek() == Some(&'{') => out.push_str("\\$"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A Nix expression for a TOML value.
pub fn literal(value: &toml::Value) -> String {
    match value {
        toml::Value::String(s) => string(s),
        toml::Value::Integer(i) => i.to_string(),
        toml::Value::Float(f) => {
            let text = format!("{f:?}");
            if text.contains('e') && !text.contains('.') { text.replacen('e', ".0e", 1) } else { text }
        }
        toml::Value::Boolean(b) => b.to_string(),
        toml::Value::Datetime(d) => string(&d.to_string()),
        toml::Value::Array(items) => {
            let items: Vec<String> = items.iter().map(literal).collect();
            if items.is_empty() { "[ ]".into() } else { format!("[ {} ]", items.join(" ")) }
        }
        toml::Value::Table(table) => {
            let fields: Vec<String> = table.iter().map(|(k, v)| format!("{} = {};", attr(k), literal(v))).collect();
            if fields.is_empty() { "{ }".into() } else { format!("{{ {} }}", fields.join(" ")) }
        }
    }
}

/// The options file for `schema` (the output of [`crate::schema_json`]): a function of
/// `{ lib, tomlType }` returning an attribute set of options. `tomlType` types the shapes the
/// generator does not model, such as tagged unions.
pub fn options_module(schema: &Value) -> String {
    let mut out = String::from(
        "# Generated by nd-hm-gen from settings.schema.json. Edit the Rust struct, not this file.\n\
         { lib, tomlType }:\n\
         let\n  t = lib.types;\n\
         \x20 opt =\n    type: description:\n    lib.mkOption {\n      type = t.nullOr type;\n      default = null;\n      inherit description;\n    };\n\
         in\n",
    );
    out.push_str(&options(&root_props(schema), 0));
    out.push('\n');
    out
}

/// `{ ... }` with the options of `props`; the closing brace sits at `depth`, the options one
/// level in. The caller places the opening brace.
fn options(props: &[Prop], depth: usize) -> String {
    let pad = "  ".repeat(depth);
    let mut out = String::from("{\n");
    for prop in props {
        let name = attr(&prop.name);
        match &prop.ty {
            Ty::Object(children) => {
                out.push_str(&format!(
                    "{pad}  {name} = lib.mkOption {{\n{pad}    type = t.submodule {{\n{pad}      options = {};\n{pad}    }};\n{pad}    default = {{ }};\n{pad}    description = {};\n{pad}  }};\n",
                    options(children, depth + 3),
                    string(prop.doc.as_deref().unwrap_or_default()),
                ));
            }
            ty => {
                out.push_str(&format!(
                    "{pad}  {name} = opt {} {};\n",
                    nix_type(ty, depth + 1),
                    string(&describe(prop))
                ));
            }
        }
    }
    out.push_str(&format!("{pad}}}"));
    out
}

fn describe(prop: &Prop) -> String {
    let mut text = prop.doc.clone().unwrap_or_default();
    if let Some(default) = prop.default.as_ref().filter(|d| !d.is_null()) {
        if !text.is_empty() {
            text.push_str("\n\n");
        }
        text.push_str(&format!("The app's default is `{default}`; leave unset to keep it."));
    }
    text
}

/// A Nix type expression that can be passed as one function argument.
fn nix_type(ty: &Ty, depth: usize) -> String {
    let wrap = |s: String| format!("({s})");
    match ty {
        Ty::Bool => "t.bool".into(),
        Ty::Int { min, max } => match (min, max) {
            (Some(lo), Some(hi)) => wrap(format!("t.ints.between {} {}", int(*lo), int(*hi))),
            (Some(lo), None) if *lo == 0.0 => "t.ints.unsigned".into(),
            (Some(lo), None) if *lo == 1.0 => "t.ints.positive".into(),
            _ => "t.int".into(),
        },
        Ty::Number { min, max } => match (min, max) {
            (Some(lo), Some(hi)) => wrap(format!("t.numbers.between {} {}", num(*lo), num(*hi))),
            _ => "t.number".into(),
        },
        Ty::Str => "t.str".into(),
        Ty::Enum(choices) => {
            let values: Vec<String> = choices.iter().map(|c| string(&c.value)).collect();
            wrap(format!("t.enum [ {} ]", values.join(" ")))
        }
        Ty::List(inner) => wrap(format!("t.listOf {}", nix_type(inner, depth))),
        Ty::Map(inner) => wrap(format!("t.attrsOf {}", nix_type(inner, depth))),
        Ty::Nullable(inner) => nix_type(inner, depth),
        Ty::Object(children) => wrap(format!("t.submodule {{ options = {}; }}", options(children, depth))),
        Ty::Any => "tomlType".into(),
    }
}

fn int(v: f64) -> String {
    format!("{}", v as i64)
}

fn num(v: f64) -> String {
    if v.fract() == 0.0 { format!("{}", v as i64) } else { format!("{v}") }
}
